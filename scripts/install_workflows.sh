FULL_SCRIPT='export LANG=en_US.UTF-8
export LC_ALL=en_US.UTF-8
results=()
for f in "$@"; do
    f="${f%/}"
    [[ -z "$f" ]] &amp;&amp; f="/"
    results+=("$f")
done
printf "%s" "${(F)results}" | pbcopy'

