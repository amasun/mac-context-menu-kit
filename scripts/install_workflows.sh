DIR_SCRIPT='export LANG=en_US.UTF-8
export LC_ALL=en_US.UTF-8
results=()
for f in "$@"; do
    f="${f%/}"
    [[ -z "$f" ]] &amp;&amp; f="/"
    if [[ -d "$f" &amp;&amp; ! "$f" =~ \.(app|bundle|framework|plugin|prefPane|qlgenerator|saver|wdgt|workflow|xcodeproj|xcworkspace)$ ]]; then
        dir="$f"
    else
        dir="$(dirname "$f")"
    fi
    results+=("$dir")
done
typeset -U results
printf "%s" "${(F)results}" | pbcopy'

